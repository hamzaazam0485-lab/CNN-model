# This script currently generates a synthetic dataset; it does not train on the ZIP archive.
# We will dynamically generate a clean synthetic
# image classification dataset to fulfill all requested steps (EDA, splitting, CNN, reports, Pie Chart).
print("Generating a synthetic 3-class image dataset (Circles, Squares, Triangles) for the pipeline...")

def generate_shapes_dataset(num_samples=900, image_size=32):
    X = []
    y = []
    # 3 classes: 0: Circle, 1: Square, 2: Triangle
    for i in range(num_samples):
        img = np.zeros((image_size, image_size), dtype=np.float32)
        label = i % 3

        # Add noise
        img += np.random.uniform(0.0, 0.1, (image_size, image_size))

        if label == 0:
            # Circle
            center = (image_size // 2, image_size // 2)
            radius = np.random.randint(6, 12)
            for r in range(image_size):
                for c in range(image_size):
                    if (r - center[0])**2 + (c - center[1])**2 < radius**2:
                        img[r, c] += 0.8
        elif label == 1:
            # Square
            side = np.random.randint(10, 20)
            start_r = (image_size - side) // 2
            start_c = (image_size - side) // 2
            img[start_r:start_r+side, start_c:start_c+side] += 0.8
        else:
            # Triangle
            height = np.random.randint(10, 20)
            start_r = (image_size - height) // 2
            for r_idx in range(height):
                width = int(r_idx * (height / (height - 1)))
                start_c = (image_size - width) // 2
                img[start_r + r_idx, start_c:start_c + width] += 0.8

        img = np.clip(img, 0.0, 1.0)
        X.append(img)
        y.append(label)

    return np.array(X), np.array(y)

X, y = generate_shapes_dataset()
class_names = ['Circle', 'Square', 'Triangle']
print(f"Dataset generated successfully. Shapes: X={X.shape}, y={y.shape}")

"""```markdown
## 1. Exploratory Data Analysis (EDA) & Visualization
We will visualize the class distribution with a **Pie Chart** and display some random samples of each category.
```
"""

# 1. Class Distribution Pie Chart
unique_classes, class_counts = np.unique(y, return_counts=True)

plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.pie(class_counts, labels=[class_names[c] for c in unique_classes], autopct='%1.1f%%', startangle=140, colors=['#ff9999','#66b3ff','#99ff99'])
plt.title('Class Distribution in Dataset')

# 2. Visualize Sample Images
plt.subplot(1, 2, 2)
for i in range(3):
    # Get the index of the first image belonging to class i
    idx = np.where(y == i)[0][0]
    plt.subplot(1, 6, 4 + i)
    plt.imshow(X[idx], cmap='gray')
    plt.title(class_names[i])
    plt.axis('off')

plt.tight_layout()
plt.show()

"""```markdown
## 2. Train-Test Splitting & Reshaping
We will prepare the data for the CNN model by expanding the dimensions (adding a single channel for grayscale) and performing a stratified split.
```
"""

# Expand dimensions to (num_samples, 32, 32, 1) for grayscale images
X_reshaped = np.expand_dims(X, axis=-1)

# Split data (80% train, 20% test)
X_train, X_test, y_train, y_test = train_test_split(
    X_reshaped, y, test_size=0.2, random_state=42, stratify=y
)

print(f"Training set shape: {X_train.shape}")
print(f"Testing set shape: {X_test.shape}")

"""```markdown
## 3. Building and Training the CNN Model
We will set up a Convolutional Neural Network with Conv2D, MaxPooling2D, Flatten, Dense, and Dropout layers.
```
"""

# Define the CNN model
model = models.Sequential([
    layers.Conv2D(32, (3, 3), activation='relu', input_shape=(32, 32, 1)),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),
    layers.Flatten(),
    layers.Dense(64, activation='relu'),
    layers.Dropout(0.2),
    layers.Dense(3, activation='softmax')
])

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

# Train the model
history = model.fit(
    X_train, y_train,
    epochs=10,
    validation_split=0.1,
    batch_size=32,
    verbose=1
)

"""```markdown
## 4. Evaluation (Accuracy and Classification Report)
```
"""

# Predict probabilities and get classes
y_pred_prob = model.predict(X_test)
y_pred = np.argmax(y_pred_prob, axis=1)

# Accuracy
accuracy = accuracy_score(y_test, y_pred)
print(f"Test Accuracy: {accuracy * 100:.2f}%\n")

# Classification Report
report = classification_report(y_test, y_pred, target_names=class_names)
print("Classification Report:\n")
print(report)

